ALTER TABLE categorias ADD CONSTRAINT uk_categorias_id_organizacao UNIQUE (id, organizacao_id);
CREATE TABLE produtos (
    id BIGINT NOT NULL AUTO_INCREMENT,
    organizacao_id BIGINT NOT NULL,
    categoria_id BIGINT NOT NULL,
    nome VARCHAR(200) NOT NULL,
    codigo_barras VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    descricao VARCHAR(4000),
    marca VARCHAR(100),
    unidade_medida VARCHAR(10) NOT NULL,
    permite_venda_fracionada BOOLEAN NOT NULL DEFAULT FALSE,
    controla_lote BOOLEAN NOT NULL DEFAULT FALSE,
    controla_validade BOOLEAN NOT NULL DEFAULT FALSE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    versao BIGINT NOT NULL DEFAULT 0,
    imagem_chave VARCHAR(40),
    fiscal_ncm VARCHAR(8), fiscal_cest VARCHAR(7), fiscal_cfop_padrao VARCHAR(4),
    fiscal_pis_cst VARCHAR(2), fiscal_cofins_cst VARCHAR(2), fiscal_origem VARCHAR(1),
    fiscal_icms_cst VARCHAR(2), fiscal_icms_csosn VARCHAR(3), fiscal_icms_modalidade_base VARCHAR(2),
    fiscal_icms_aliquota DECIMAL(7,4), fiscal_icms_reducao_base DECIMAL(7,4),
    criado_em TIMESTAMP(6) NOT NULL,
    atualizado_em TIMESTAMP(6) NOT NULL,
    criado_por BIGINT NOT NULL,
    atualizado_por BIGINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_produtos_organizacao_codigo UNIQUE (organizacao_id, codigo_barras),
    CONSTRAINT fk_produtos_organizacao FOREIGN KEY (organizacao_id) REFERENCES organizacoes (id),
    CONSTRAINT fk_produtos_categoria FOREIGN KEY (categoria_id, organizacao_id) REFERENCES categorias (id, organizacao_id),
    CONSTRAINT fk_produtos_criado_por FOREIGN KEY (criado_por) REFERENCES usuarios (id),
    CONSTRAINT fk_produtos_atualizado_por FOREIGN KEY (atualizado_por) REFERENCES usuarios (id),
    CONSTRAINT ck_produtos_unidade CHECK (unidade_medida IN ('UN','KG','G','L','ML','CX','PCT')),
    CONSTRAINT ck_produtos_icms_situacao CHECK (fiscal_icms_cst IS NULL OR fiscal_icms_csosn IS NULL),
    CONSTRAINT ck_produtos_icms_aliquota CHECK (fiscal_icms_aliquota BETWEEN 0 AND 100),
    CONSTRAINT ck_produtos_icms_reducao CHECK (fiscal_icms_reducao_base BETWEEN 0 AND 100),
    INDEX ix_produtos_org_ativo_nome (organizacao_id, ativo, nome),
    INDEX ix_produtos_org_categoria (organizacao_id, categoria_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
